<#
.SYNOPSIS  Regenerates docs/PARAMETERS.md and docs/CONFIGURATION.md from aic.ps1 itself (parameter block, comment-based help, config schema).
.PARAMETER Check  Do not write: exit 1 when the committed files differ from what would be generated.
#>
param([string]$AicPath = (Join-Path $PSScriptRoot '..' 'aic.ps1'), [string]$OutDir = (Join-Path $PSScriptRoot '..' 'docs'), [switch]$Check)
$src = Get-Content -LiteralPath $AicPath -Raw
$ast = [System.Management.Automation.Language.Parser]::ParseFile((Resolve-Path $AicPath).Path, [ref]$null, [ref]$null)
$fn  = $ast.Find({ param($n) $n -is [System.Management.Automation.Language.FunctionDefinitionAst] -and $n.Name -eq 'aic' }, $true)

# ---- parameters ----
$help = @{}
foreach ($m in [regex]::Matches($src, '(?ms)^\.PARAMETER (\w+)\r?\n(.*?)(?=^\.PARAMETER |^\.NOTES|^\.EXAMPLE|^#>)')) {
    $help[$m.Groups[1].Value] = (($m.Groups[2].Value -split '\r?\n' | ForEach-Object { $_.Trim() } | Where-Object { $_ }) -join ' ')
}
$rows = foreach ($p in $fn.Body.ParamBlock.Parameters) {
    $name = $p.Name.VariablePath.UserPath
    $type = $p.StaticType.Name; if ($type -eq 'SwitchParameter') { $type = 'switch' }
    $vs   = @($p.Attributes | Where-Object { $_.TypeName.Name -eq 'ValidateSet' } | ForEach-Object { $_.PositionalArguments | ForEach-Object { $_.Value } })
    $vr   = @($p.Attributes | Where-Object { $_.TypeName.Name -eq 'ValidateRange' } | ForEach-Object { ($_.PositionalArguments | ForEach-Object { $_.Extent.Text }) -join '..' })
    $al   = @($p.Attributes | Where-Object { $_.TypeName.Name -eq 'Alias' } | ForEach-Object { $_.PositionalArguments | ForEach-Object { $_.Value } })
    $def  = if ($p.DefaultValue) { $p.DefaultValue.Extent.Text } else { '' }
    $rest = @(); if ($vs.Count) { $rest += "one of: $($vs -join ', ')" }; if ($vr.Count) { $rest += "range $($vr[0])" }; if ($al.Count) { $rest += "alias: -$($al -join ', -')" }
    [pscustomobject]@{ Name = $name; Type = $type; Default = $def; Notes = ($rest -join '; '); Help = $help[$name] }
}
$pm = [System.Collections.Generic.List[string]]::new()
$pm.Add('# Parameter reference'); $pm.Add('')
$pm.Add('_Generated by `tools/Update-Docs.ps1` from the parameter block and comment-based help of `aic.ps1`: do not edit by hand. `Get-Help aic -Full` shows the same text._'); $pm.Add('')
$pm.Add("aic has $($rows.Count) parameters. Settings precedence: flag you type > `$PSDefaultParameterValues > .aic.json in the repo > ~/.aic.json > built-in default."); $pm.Add('')
$pm.Add('| Parameter | Type | Default | Constraints | Description |'); $pm.Add('|---|---|---|---|---|')
foreach ($r in $rows) { $pm.Add("| ``-$($r.Name)`` | $($r.Type) | $(if ($r.Default) { '`' + $r.Default.Replace('|','\|') + '`' } else { '' }) | $($r.Notes) | $(($r.Help -as [string]).Replace('|','\|')) |") }
$params = ($pm -join "`n") + "`n"

# ---- configuration ----
$desc = @{
    model = 'Ollama / server model name.'; language = 'Language of the subject and bullets (type and scope stay English).'; coAuthor = 'Adds a "Co-authored-by: ..." footer to every commit.'
    bullets = 'Maximum body bullets (0 = subject line only).'; history = 'How many recent commit subjects the model sees as a style reference.'; width = 'Maximum card width.'
    provider = 'Which kind of server to talk to.'; profile = 'Model profile, used only when no "model" is configured. An explicitly typed -Model always wins.'
    theme = 'Colour theme.'; spinner = 'Spinner animation.'; border = 'Card border style.'; banner = 'Header style.'
    emoji = 'Gitmoji after the colon.'; autoStageAi = 'Every run behaves like -AiFiles.'; lint = 'Built-in leftover / conflict-marker / large-file checks.'; autoRef = 'Derive a "Refs:" footer from the branch name.'
    exclude = 'Extra pathspecs hidden from the MODEL (they are still scanned for secrets and still committed).'; scopes = 'Allowed commit scopes (case-sensitive). Also used to pick scopes with the s key.'; aiFiles = 'Extra globs that count as AI-related files.'
}
$schema = [regex]::Match($src, '(?s)\$cfgSchema = @\{(.*?)\n    \}').Groups[1].Value
$keys = [ordered]@{}
foreach ($m in [regex]::Matches($schema, '(\w+) = ''([^'']+)''')) { $keys[$m.Groups[1].Value] = $m.Groups[2].Value }
foreach ($m in [regex]::Matches($schema, '(\w+) = "enum:\$\(\$valid(\w+) ')) { $keys[$m.Groups[1].Value] = 'enum:' + $m.Groups[2].Value }
$enums = @{ Themes = 'ocean, sunset, forest, neon, mono, aurora, rose, gold, dracula, candy'; Spinners = 'dots, arc, bounce, pulse, grow, line, star, orbit'; Borders = 'rounded, square, double, heavy'; Banners = 'mini, big, none' }
$cm = [System.Collections.Generic.List[string]]::new()
$cm.Add('# Configuration reference'); $cm.Add('')
$cm.Add('_The key table is generated by `tools/Update-Docs.ps1` from the schema in `aic.ps1`._'); $cm.Add('')
$cm.Add('Two optional JSON files hold defaults: `~/.aic.json` (personal, every repo) and `<repo>/.aic.json` (wins over the personal file). A flag you type wins over both. `aic -Init` writes a starter file; `aic -ConfigValidate` checks both files without contacting any server (exit 0 = valid, 1 = problems).'); $cm.Add('')
$cm.Add('Every key is validated. Unknown keys get a "did you mean" hint, wrong types and invalid values are reported and ignored, out-of-range numbers are clamped and reported. A repo list (`scopes`, `exclude`, `aiFiles`) replaces the personal one only for keys it sets; lists are not merged.'); $cm.Add('')
$cm.Add('| Key | Type | Values | Description |'); $cm.Add('|---|---|---|---|')
foreach ($k in $keys.Keys) {
    $spec = $keys[$k] -split ':'; $vals = ''
    $type = switch ($spec[0]) { 'string' { 'text' } 'bool' { 'true / false' } 'int' { 'whole number'; $vals = "$($spec[1]) to $($spec[2])" } 'list' { 'list of text' } 'enum' { 'text' } }
    if ($spec[0] -eq 'int') { $vals = "$($spec[1]) to $($spec[2])" }
    if ($spec[0] -eq 'enum') { $vals = if ($spec[1] -cmatch '^[A-Z]') { $enums[$spec[1]] } else { ($spec[1] -split ',') -join ', ' } }
    $cm.Add("| ``$k`` | $type | $vals | $($desc[$k]) |")
}
$cm.Add(''); $cm.Add('## Example'); $cm.Add(''); $cm.Add('```json'); $cm.Add('{'); $cm.Add('  "model": "qwen2.5-coder:7b",'); $cm.Add('  "language": "English",'); $cm.Add('  "bullets": 3,'); $cm.Add('  "scopes": ["api", "ui", "docs"],'); $cm.Add('  "exclude": ["*.svg"],'); $cm.Add('  "aiFiles": ["prompts/*", "*.prompt.md"],'); $cm.Add('  "lint": true,'); $cm.Add('  "autoRef": true'); $cm.Add('}'); $cm.Add('```'); $cm.Add('')
$cm.Add('## Environment variables'); $cm.Add('')
$cm.Add('| Variable | Effect |'); $cm.Add('|---|---|')
$cm.Add('| `OLLAMA_HOST` | Server address for the Ollama provider (`:11434`, `host:port`, `0.0.0.0:11434` are accepted). |')
$cm.Add('| `AIC_API_KEY` | Optional Bearer token sent to the server (any provider). Read from the environment only; never printed, logged or written to a config file. |')
$cm.Add('| `NO_COLOR` | Disables colour. |')
$config = ($cm -join "`n") + "`n"

$targets = @{ 'PARAMETERS.md' = $params; 'CONFIGURATION.md' = $config }
$bad = 0
foreach ($t in $targets.Keys) {
    $path = Join-Path $OutDir $t
    if ($Check) { $cur = if (Test-Path $path) { (Get-Content $path -Raw) -replace "`r`n", "`n" } else { '' }; if ($cur -ne $targets[$t]) { Write-Host "OUT OF DATE: $t"; $bad++ } }
    else { [IO.File]::WriteAllText($path, $targets[$t], [Text.UTF8Encoding]::new($false)); Write-Host "wrote $path" }
}
if ($Check -and $bad) { exit 1 }
